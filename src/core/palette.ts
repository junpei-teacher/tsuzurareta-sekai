  // 減色をやめて絵が暖色・高彩度になったので、UIだけ冷たい黒のままだと浮く
  panel:   "#241d18",
  line:    "#5c4a38", // 枠線専用。文字には使わない
  ink:     "#e8dcc0", // 本文
