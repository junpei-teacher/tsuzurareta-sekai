// 全画面で共通のUIパレット。
//
// 【文字色の規約】
//
//   ink   本文。読ませる文字は必ずこれ
//   dim   補助。数値・ラベル・説明文
//   hint  操作ヒントだけ（「ESC もどる」など）。**本文には使わない**
//   line  **枠線専用。文字に使ってはならない**
//
// line は暗い背景に対して 1.5 程度しかコントラストが無い。
// 枠として1px引くぶんには十分だが、文字に使うと事実上見えない。
// 以前これを「TAB 候補」「（呪文帳にない言葉）」などの文字色に使っていて、
// 減色をやめて絵が明るくなったあと、目が明るさに慣れて読めなくなった。
// **絵が明るくなるほど、暗いUI文字は読めなくなる。**
//
// 第二作では屋外の色数が増える。本文と操作ヒントが背景へ沈まないよう、
// 文字色は第一作より一段明るくしてある。土地そのものの色は theme.ts が持つ。

