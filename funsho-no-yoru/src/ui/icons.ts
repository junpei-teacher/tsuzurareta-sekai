/** 絵記号の一辺（デザイン単位）。行に置くときの幅の目安にする */
export const ICON_SIZE = N;

/**
 * 属性の絵記号を描く。左上を (x, y) に置く。
 * @param fade 1未満にすると薄く出る。効かない属性を並べるときに使う
 */
export function elementIcon(d: Display, x: number, y: number, el: Element, fade = 1): void {
  const icon = ICONS[el];
  if (!icon) return;
  if (fade < 1) d.ctx.globalAlpha = fade;
  for (let row = 0; row < N; row++) {
    const line = icon.art[row] ?? "";
    for (let col = 0; col < N; col++) {
      const c = line[col];
      if (!c || c === ".") continue;
      const color = icon.colors[c];
      if (color) d.rect(x + col, y + row, 1, 1, color);
    }
  }
  if (fade < 1) d.ctx.globalAlpha = 1;
}
